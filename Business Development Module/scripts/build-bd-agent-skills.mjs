// Bundles the Business Development Agent skills (installed from skills.sh into
// Agent Module/05_Business_Development_Agent/.claude/skills) into
// supabase/bd-agent/skills.ts, so the bd-agent Edge Function can use them.
//
// Run from anywhere:  node "Business Development Module/scripts/build-bd-agent-skills.mjs"
// Re-run after `npx skills update` or after adding/removing skills, then redeploy bd-agent.

import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const skillsDir = join(here, "..", "..", "Agent Module", "05_Business_Development_Agent", ".claude", "skills");
const agentSpec = join(here, "..", "..", "Agent Module", "05_Business_Development_Agent", "CLAUDE.md");
const out = join(here, "..", "supabase", "bd-agent", "skills.ts");
const MAX_BODY = 14000; // characters of each SKILL.md body sent to the model

function frontmatter(text) {
  const match = text.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?/);
  if (!match) return { meta: {}, body: text };
  const meta = {};
  let key = null;
  for (const line of match[1].split(/\r?\n/)) {
    const pair = line.match(/^([A-Za-z_-]+):\s*(.*)$/);
    if (pair) { key = pair[1]; meta[key] = pair[2].replace(/^["']|["']$/g, ""); }
    else if (key && /^\s+/.test(line)) meta[key] += " " + line.trim();
  }
  return { meta, body: text.slice(match[0].length) };
}

const skills = [];
for (const name of readdirSync(skillsDir).sort()) {
  const file = join(skillsDir, name, "SKILL.md");
  if (!existsSync(file)) continue;
  const { meta, body } = frontmatter(readFileSync(file, "utf8"));
  const trimmed = body.trim();
  skills.push({
    name: meta.name || name,
    description: (meta.description || "").replace(/\s+/g, " ").trim(),
    body: trimmed.length > MAX_BODY ? trimmed.slice(0, MAX_BODY) + "\n\n[Skill text shortened for this agent.]" : trimmed,
  });
}

const spec = readFileSync(agentSpec, "utf8");
writeFileSync(out, `// Generated by scripts/build-bd-agent-skills.mjs. Do not edit by hand.
export type Skill = { name: string; description: string; body: string };
export const AGENT_SPEC: string = ${JSON.stringify(spec)};
export const SKILLS: Skill[] = ${JSON.stringify(skills, null, 1)};
`);
console.log(`Wrote ${skills.length} skills to ${out}`);
