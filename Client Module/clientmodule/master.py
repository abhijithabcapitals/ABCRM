"""Client master database: ONE CLIENT = ONE ROW, fixed 134-column header (schema.json).

    data/client-master.csv      master file (UTF-8 with BOM so Excel opens it correctly)
    data/Client_Master.xlsx     formatted Excel copy, regenerated by export_xlsx()
    data/change-log.csv         append-only field-level history (old -> new) for every save
    data/backups/               copy of the master taken before every write
    data/client-id-counter.txt  highest Client ID ever issued (CL000001 ...), so IDs are never reused

Rules: blank incoming values never overwrite stored data, blanks become Not Provided, fields whose condition
is false become N/A, nothing is inferred, and a likely duplicate stops a new save.
"""
from __future__ import annotations

import csv
import getpass
import json
import math
import os
import re
import shutil
import threading
from datetime import date, datetime, timedelta, timezone
from pathlib import Path
from typing import Any

from .config import PACKAGE_DIR

DASH = "–"
PART_SEP = f" {DASH} "
NP = "Not Provided"
NA = "N/A"
VR = f"Provided {DASH} Verification Required"
VR_SUFFIX = f" ({VR})"
ID_PREFIX = "CL"
ID_RE = re.compile(r"^CL(\d{6,})$")
DUBAI = timezone(timedelta(hours=4))
_LIST_SPLIT = re.compile(r"\s[–\-]\s")

Record = dict[str, str]


def dubai_now() -> datetime:
    return datetime.now(DUBAI)


def today() -> date:
    return dubai_now().date()


# ---------- schema ----------

class Schema:
    def __init__(self, path: Path = PACKAGE_DIR / "schema.json"):
        self.raw = json.loads(path.read_text(encoding="utf-8"))
        self.columns: list[str] = list(self.raw["columns"])
        self.auto: list[str] = list(self.raw["auto"])
        self.fields: dict[str, dict[str, Any]] = {}
        for st in self.raw["stages"]:
            for f in st["fields"]:
                self.fields[f["col"]] = {**f, "stage": st["title"]}
        defined = set(self.fields) | set(self.auto)
        missing = [c for c in self.columns if c not in defined]
        extra = [c for c in defined if c not in self.columns]
        if len(self.columns) != 134 or missing or extra:
            raise ValueError(f"Schema mismatch: {len(self.columns)} columns; not defined: {missing}; unknown: {extra}")


# ---------- value helpers ----------

def blank(v: str | None) -> bool:
    return v is None or not str(v).strip()


def unknown(v: str | None) -> bool:
    """True when the cell holds no usable information."""
    return blank(v) or v == NP or v == VR


def needs_verification(v: str | None) -> bool:
    return bool(v) and (v == VR or v.endswith(VR_SUFFIX))


def plain(v: str | None) -> str:
    v = v or ""
    if v == VR:
        return ""
    return v[: -len(VR_SUFFIX)] if v.endswith(VR_SUFFIX) else v


def parse_uae_date(v: str | None) -> date | None:
    try:
        return datetime.strptime(plain(v).strip(), "%d/%m/%Y").date()
    except ValueError:
        return None


def split_cell(v: str | None) -> list[str]:
    if unknown(v) or v == NA:
        return []
    return [x.strip() for x in plain(v).split(";") if x.strip()]


def list_from_cell(v: str | None, field: dict[str, Any]) -> list[dict[str, str]]:
    """List cells: items separated by '; ', parts by ' – '; first part bare, the rest 'Key: value'."""
    first = field["sub"][0]["key"]
    out = []
    for item in split_cell(v):
        parts = _LIST_SPLIT.split(item)
        h = {first: parts[0].strip()}
        for p in parts[1:]:
            i = p.find(":")
            if i > 0:
                h[p[:i].strip()] = p[i + 1:].strip()
        out.append(h)
    return out


def _clean_part(s: str) -> str:
    return re.sub(r"[\r\n]+", " ", _LIST_SPLIT.sub("-", str(s or "").replace(";", ","))).strip()


def list_to_cell(items: list[dict[str, str]], field: dict[str, Any]) -> str:
    subs = field["sub"]
    out = []
    for it in items:
        first = _clean_part(it.get(subs[0]["key"], ""))
        rest = [f"{s['key']}: {_clean_part(it.get(s['key'], ''))}" for s in subs[1:] if _clean_part(it.get(s["key"], ""))]
        if first or rest:
            out.append(PART_SEP.join([first or "Unnamed", *rest]))
    return "; ".join(out)


def docs_from_cell(v: str | None) -> dict[str, str]:
    """Docs cells: 'Trade License: Received; MOA: Missing'."""
    h: dict[str, str] = {}
    for item in split_cell(v):
        i = item.rfind(":")
        if i > 0:
            h[item[:i].strip()] = item[i + 1:].strip()
    return h


def docs_to_cell(statuses: dict[str, str], field: dict[str, Any]) -> str:
    return "; ".join(f"{d}: {statuses[d]}" for d in field["docs"] if statuses.get(d))


_SUFFIX_WORDS = re.compile(r"\b(l\s?l\s?c|fz\s?llc|fz\s?co|fze|fzc|llc|est|establishment|company|co|ltd|limited|plc|branch"
                           r"|the|sole|proprietorship|l l c)\b")


def normal_name(v: str | None) -> str:
    n = re.sub(r"[^a-z0-9 ]", " ", plain(v).lower())
    return re.sub(r"\s+", " ", _SUFFIX_WORDS.sub(" ", n)).strip()


def normal_id(v: str | None) -> str:
    if unknown(v) or v == NA:
        return ""
    return re.sub(r"[^A-Za-z0-9]", "", plain(v)).upper()


def normal_phone(v: str | None) -> str:
    d = re.sub(r"\D", "", plain(v))
    return d[-9:] if len(d) >= 9 else ""


# ---------- the store ----------

class ClientMaster:
    def __init__(self, data_dir: Path, schema: Schema | None = None):
        self.schema = schema or Schema()
        self.data_dir = data_dir
        self.csv_path = data_dir / "client-master.csv"
        self.xlsx_path = data_dir / "Client_Master.xlsx"
        self.change_log = data_dir / "change-log.csv"
        self.backup_dir = data_dir / "backups"
        self.counter_file = data_dir / "client-id-counter.txt"
        self.lock = threading.RLock()
        self.backup_dir.mkdir(parents=True, exist_ok=True)
        if not self.csv_path.exists():
            self._write([])

    @property
    def columns(self) -> list[str]:
        return self.schema.columns

    @property
    def fields(self) -> dict[str, dict[str, Any]]:
        return self.schema.fields

    # ---- file io ----
    def read(self) -> list[Record]:
        with self.lock:
            if not self.csv_path.exists():
                return []
            with open(self.csv_path, encoding="utf-8-sig", newline="") as fh:
                return [{c: str(r.get(c) or "") for c in self.columns} for r in csv.DictReader(fh)]

    def _write(self, rows: list[Record]) -> None:
        if self.csv_path.exists():
            stamp = datetime.now().strftime("%Y%m%d-%H%M%S-%f")[:-3]
            shutil.copyfile(self.csv_path, self.backup_dir / f"client-master-{stamp}.csv")
        tmp = self.csv_path.with_suffix(".csv.tmp")
        with open(tmp, "w", encoding="utf-8-sig", newline="") as fh:
            w = csv.DictWriter(fh, fieldnames=self.columns, quoting=csv.QUOTE_ALL)
            w.writeheader()
            for r in rows:
                w.writerow({c: r.get(c, "") for c in self.columns})
        try:
            os.replace(tmp, self.csv_path)
        except PermissionError as exc:
            tmp.unlink(missing_ok=True)
            raise RuntimeError("Could not write client-master.csv - close it in Excel and try again.") from exc

    def get(self, client_id: str) -> Record | None:
        return next((r for r in self.read() if r["Client ID"] == client_id), None)

    def next_id(self, rows: list[Record]) -> str:
        top = 0
        if self.counter_file.exists():
            txt = self.counter_file.read_text(encoding="ascii").strip()
            top = int(txt) if txt.isdigit() else 0
        for r in rows:
            m = ID_RE.match(r["Client ID"])
            if m:
                top = max(top, int(m.group(1)))
        nxt = top + 1
        self.counter_file.write_text(str(nxt), encoding="ascii")
        return f"{ID_PREFIX}{nxt:06d}"

    # ---- duplicates ----
    def find_duplicates(self, rec: Record, exclude_id: str = "", rows: list[Record] | None = None) -> list[dict[str, Any]]:
        """Likely duplicates by legal/trade name, licence, registration number, TRN, CT number, email or phone."""
        rows = self.read() if rows is None else rows
        name, trade = normal_name(rec.get("Client Legal Name")), normal_name(rec.get("Trade Name"))
        ids = {k: normal_id(rec.get(k)) for k in ("Trade License Number", "Company Registration Number", "TRN",
                                                  "CT Registration Number")}
        email = plain(rec.get("General Email")).strip().lower()
        phone = normal_phone(rec.get("General Phone"))
        hits = []
        for r in rows:
            if exclude_id and r["Client ID"] == exclude_id:
                continue
            why = []
            rn = normal_name(r["Client Legal Name"])
            if name and rn == name:
                why.append("Legal name")
            elif trade and (rn == trade or normal_name(r["Trade Name"]) == trade):
                why.append("Trade name")
            why += [k for k, v in ids.items() if v and normal_id(r[k]) == v]
            if email and email not in ("not provided", "n/a") and plain(r["General Email"]).strip().lower() == email:
                why.append("Email")
            if phone and normal_phone(r["General Phone"]) == phone:
                why.append("Phone")
            if why:
                hits.append({"id": r["Client ID"], "name": r["Client Legal Name"], "matches": why})
        return hits

    # ---- completion, validation, derived values ----
    @staticmethod
    def applies(field: dict[str, Any], rec: Record) -> bool:
        cond = field.get("when")
        if not cond:
            return True
        v = plain(rec.get(cond["col"]))
        if "eq" in cond:
            return v == cond["eq"]
        if "ne" in cond:
            return not unknown(v) and v != NA and v != cond["ne"]
        return True

    @staticmethod
    def field_score(field: dict[str, Any], v: str) -> float:
        """1 known, 0.5 provided-but-unverified, 0 unknown. Docs: share of documents received / not applicable."""
        if field["type"] == "docs":
            st = docs_from_cell(v)
            pts = sum({"Received": 1, "Not Applicable": 1, "Under Review": 0.5}.get(st.get(d, ""), 0) for d in field["docs"])
            return pts / len(field["docs"])
        if unknown(v):
            return 0.5 if v == VR else 0
        return 0.5 if needs_verification(v) else 1

    def auto_review(self, rec: Record) -> list[str]:
        """Review items derived from the record itself (validation flags + fields marked for verification)."""
        items: list[str] = []
        add = lambda t: items.append(t) if t not in items else None  # noqa: E731
        now = today()
        exp, iss = parse_uae_date(rec.get("License Expiry Date")), parse_uae_date(rec.get("License Issue Date"))
        if exp and exp < now:
            add("License Expired / Review Required")
        elif exp and exp <= now + timedelta(days=30):
            add("License Expiring Within 30 Days")
        if exp and iss and iss > exp:
            add("License Dates Inconsistent")

        vat_reg = plain(rec.get("VAT Registered"))
        if vat_reg == "Yes" and unknown(rec.get("TRN")):
            add("VAT Information Incomplete")
        trn = normal_id(rec.get("TRN"))
        if trn and not re.fullmatch(r"\d{15}", trn):
            add("TRN Format Check (expected 15 digits)")
        services = split_cell(rec.get("Services Provided"))
        if vat_reg == "No" and "VAT Return Filing" in services:
            add("VAT Review Required")

        ct_reg = plain(rec.get("Corporate Tax Registered"))
        if ct_reg == "Yes" and unknown(rec.get("CT Registration Number")):
            add("CT Information Incomplete")
        if ct_reg == "No" and "Corporate Tax Return" in services:
            add("Corporate Tax Registration Review Required")

        audit = plain(rec.get("Audit Required"))
        if (audit == "Yes" or "Audit" in services) and (unknown(rec.get("Audit Period")) or rec.get("Audit Period") == NA):
            add("Audit Information Incomplete")

        sh = list_from_cell(rec.get("Shareholders"), self.fields["Shareholders"])
        if sh:
            pcts = [s.get("Ownership", "") for s in sh if re.fullmatch(r"\s*[\d.]+\s*%?\s*", s.get("Ownership", ""))]
            if len(pcts) == len(sh):
                total = sum(float(re.sub(r"[%\s]", "", p)) for p in pcts)
                if abs(total - 100) > 0.01:
                    add(f"Shareholding Totals {total:g}% (expected 100%)")
            if any(s.get("Type") == "Corporate" for s in sh) and unknown(rec.get("UBO")):
                add("UBO Verification Required (corporate shareholder)")

        s, e = parse_uae_date(rec.get("Engagement Start Date")), parse_uae_date(rec.get("Engagement End Date"))
        if s and e and e < s:
            add("Engagement Dates Inconsistent")
        fs, fe = parse_uae_date(rec.get("Financial Year Start")), parse_uae_date(rec.get("Financial Year End"))
        if fs and fe and fe <= fs:
            add("Financial Year Dates Inconsistent")

        for f in self.fields.values():  # a value recorded for a field whose condition says it does not apply
            if f.get("when") and not self.applies(f, rec):
                v = rec.get(f["col"], "")
                if not unknown(v) and v != NA:
                    add(f"{f['col']} recorded but {f['when']['col']} = {plain(rec.get(f['when']['col']))}")
        for f in self.fields.values():
            if needs_verification(rec.get(f["col"])):
                add(f"Verify: {f['col']}")
        return items

    def manual_review(self, rec: Record) -> list[str]:
        """Items the user typed into Items Requiring Review (stored value minus the automatic items)."""
        auto = self.auto_review(rec)
        return [x for x in split_cell(rec.get("Items Requiring Review")) if x not in auto and x != "None"]

    def complete(self, incoming: dict[str, Any], existing: Record | None = None) -> dict[str, Any]:
        """Builds the final row from incoming values (plus the existing row on update) and computes every automatic column."""
        cols, fields = self.columns, self.fields
        rec: Record = {c: (existing or {}).get(c, "") or "" for c in cols}

        if incoming.get("Items Requiring Review") is not None and "Items Requiring Review" in incoming:
            manual = [x.strip() for x in re.split(r"[;\r\n]+", str(incoming["Items Requiring Review"])) if x.strip()]
        elif existing:
            manual = self.manual_review(existing)
        else:
            manual = []

        for c in cols:
            if c in self.schema.auto or c == "Items Requiring Review" or c not in incoming:
                continue
            v = str(incoming[c] if incoming[c] is not None else "").strip()
            if v:
                rec[c] = v

        contacts = list_from_cell(rec["Contact Details"], fields["Contact Details"])  # role columns come from contacts
        for f in fields.values():
            if f["type"] == "derived":
                names = [x.get("Name", "") for x in contacts if f["role"] in (x.get("Roles", "")).split("/")]
                if names:
                    rec[f["col"]] = "; ".join(names)

        for f in fields.values():
            c = f["col"]
            if f["type"] == "review":
                continue
            v = rec[c]
            if f["type"] == "yesno" and re.fullmatch(r"(?i)yes|no", v or ""):
                rec[c] = v.capitalize()
            if not self.applies(f, rec):
                if unknown(v) and v != VR:
                    rec[c] = NA
            elif blank(v) or (v == NA and f.get("when") and incoming.get(c) != NA):
                rec[c] = NP  # applies now: a blank, or an N/A left over from when its condition was false
            if blank(rec[c]):
                rec[c] = NP

        pts, n, missing = 0.0, 0, []
        for f in fields.values():
            if not f.get("req") or not self.applies(f, rec):
                continue
            w = len(f["docs"]) if f["type"] == "docs" else 1  # each document is its own item: no inflated score
            sc = self.field_score(f, rec[f["col"]])
            n += w
            pts += sc * w
            if f["type"] == "docs":
                st = docs_from_cell(rec[f["col"]])
                for d in f["docs"]:
                    s = st.get(d, "")
                    if s in ("Missing", "Expired", ""):
                        missing.append(d + (" (expired)" if s == "Expired" else " (status not set)" if not s else ""))
            elif sc == 0:
                missing.append(f["col"])
        score = math.floor(100 * pts / n) if n else 0

        auto = self.auto_review(rec)
        review = manual + [x for x in auto if x not in manual]
        stamp = dubai_now().strftime("%d/%m/%Y")
        rec["Onboarding Completion %"] = f"{score}%"
        rec["Missing Information"] = "; ".join(missing) if missing else "None"
        rec["Items Requiring Review"] = "; ".join(review) if review else "None"
        rec["Last Updated"] = stamp
        done = rec.get("Onboarding Completed Date", "")
        if plain(rec.get("Onboarding Status")) == "Active Client" and (unknown(done) or done == NA):
            rec["Onboarding Completed Date"] = stamp
        elif blank(done):
            rec["Onboarding Completed Date"] = NP

        errors = []
        if unknown(rec["Client Legal Name"]):
            errors.append("Client Legal Name is required.")
        risk = plain(rec.get("Risk Level"))
        if risk in ("High", "Review Required") and unknown(rec.get("Risk Reason")):
            errors.append(f"Risk Level is {risk} - record the Risk Reason before saving.")

        changes = []
        if existing:
            changes = [{"field": c, "old": existing.get(c, ""), "new": rec[c]} for c in cols
                       if c != "Last Updated" and (existing.get(c, "") or "") != rec[c]]
        band = ("Fully Onboarded" if score >= 90 else "Mostly Onboarded" if score >= 70
                else "Incomplete" if score >= 50 else "High Attention Required")
        return {"record": rec, "score": score, "band": band, "missing": missing, "review": review,
                "manualReview": manual, "autoReview": auto, "errors": errors, "changes": changes}

    # ---- history ----
    def add_change_log(self, client_id: str, action: str, changes: list[dict[str, str]]) -> None:
        ts = dubai_now().strftime("%d/%m/%Y %H:%M:%S")
        try:
            who = getpass.getuser()
        except Exception:
            who = ""
        lines = [{"Timestamp": ts, "Client ID": client_id, "Action": action, "Field": c["field"], "Old": c["old"],
                  "New": c["new"], "User": who} for c in changes] or [
            {"Timestamp": ts, "Client ID": client_id, "Action": action, "Field": "", "Old": "", "New": "", "User": who}]
        new_file = not self.change_log.exists()
        with open(self.change_log, "a", encoding="utf-8-sig" if new_file else "utf-8", newline="") as fh:
            w = csv.DictWriter(fh, fieldnames=list(lines[0]), quoting=csv.QUOTE_ALL)
            if new_file:
                w.writeheader()
            w.writerows(lines)

    def history(self, client_id: str) -> list[dict[str, str]]:
        if not self.change_log.exists():
            return []
        with open(self.change_log, encoding="utf-8-sig", newline="") as fh:
            return [r for r in csv.DictReader(fh) if r.get("Client ID") == client_id]

    # ---- save ----
    def save(self, incoming: dict[str, Any], client_id: str = "", confirmed: bool = False,
             allow_duplicate: bool = False) -> dict[str, Any]:
        """New client -> one new row (after a duplicate check). Existing client -> that row only.
        `confirmed` is required: the final review must have been shown and accepted."""
        if not confirmed:
            return {"ok": False, "errors": ["Not saved: the final review must be confirmed first."]}
        with self.lock:
            rows = self.read()
            existing = None
            if client_id:
                existing = next((r for r in rows if r["Client ID"] == client_id), None)
                if not existing:
                    return {"ok": False, "errors": [f"Client {client_id} not found."]}
            res = self.complete(incoming, existing)
            if res["errors"]:
                return {"ok": False, "errors": res["errors"]}
            dups = self.find_duplicates(res["record"], client_id, rows)
            if dups and not client_id and not allow_duplicate:
                return {"ok": False, "duplicates": dups, "errors": ["Likely duplicate client found - not saved."]}
            if existing:
                if not res["changes"]:
                    return {"ok": True, "id": client_id, "unchanged": True, "result": res}
                rows[rows.index(existing)] = res["record"]
                self._write(rows)
                self.add_change_log(client_id, "Updated", res["changes"])
            else:
                client_id = self.next_id(rows)
                res["record"]["Client ID"] = client_id
                rows.append(res["record"])
                self._write(rows)
                self.add_change_log(client_id, "Created (duplicate override)" if dups else "Created", [])
            return {"ok": True, "id": client_id, "result": res, "duplicates": dups}

    # ---- excel + stats ----
    def export_xlsx(self) -> Path:
        """Formatted Excel copy; every cell is text so TRNs, phones and percentages stay exact."""
        from openpyxl import Workbook
        from openpyxl.styles import Alignment, Font, PatternFill
        from openpyxl.utils import get_column_letter

        wb = Workbook()
        ws = wb.active
        ws.title = "Client Master"
        ws.append(self.columns)
        for r in self.read():
            ws.append([r.get(c, "") for c in self.columns])
        for row in ws.iter_rows():
            for cell in row:
                cell.number_format = "@"
                cell.alignment = Alignment(vertical="top", wrap_text=cell.row == 1)
        for cell in ws[1]:
            cell.font = Font(bold=True, color="FFFFFF")
            cell.fill = PatternFill("solid", fgColor="1F3A4D")
        ws.row_dimensions[1].height = 32
        for i in range(1, len(self.columns) + 1):
            ws.column_dimensions[get_column_letter(i)].width = 22
        ws.freeze_panes = "C2"
        ws.auto_filter.ref = f"A1:{get_column_letter(len(self.columns))}{ws.max_row}"
        tmp = self.xlsx_path.with_suffix(".tmp.xlsx")
        wb.save(tmp)
        try:
            os.replace(tmp, self.xlsx_path)
        except PermissionError as exc:
            tmp.unlink(missing_ok=True)
            raise RuntimeError("Excel export failed - close Client_Master.xlsx if it is open.") from exc
        return self.xlsx_path

    def stats(self, rows: list[Record]) -> dict[str, int]:
        now = today()
        scores = [int(re.sub(r"\D", "", r["Onboarding Completion %"]) or 0) for r in rows]
        lic = [parse_uae_date(r["License Expiry Date"]) for r in rows]
        return {
            "total": len(rows),
            "active": sum(r["Onboarding Status"] == "Active Client" for r in rows),
            "pending": sum(r["Onboarding Status"] not in ("Active Client", "Closed", "On Hold") for r in rows),
            "highRisk": sum(r["Risk Level"] in ("High", "Review Required") for r in rows),
            "avgScore": int(sum(scores) / len(scores)) if scores else 0,
            "licExpiring": sum(1 for d in lic if d and d <= now + timedelta(days=30)),
        }
