"""Writes migrations/003_agent_seed.sql from Agent Module: the registry plus each agent's CLAUDE.md.

    python "Database Module/AI Base/build_agent_seed.py"

Rows are inserted with ON CONFLICT DO NOTHING, so running the seed again never overwrites what an admin saved.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
AGENTS = ROOT / "Agent Module"
OUT = Path(__file__).parent / "migrations" / "003_agent_seed.sql"
SONNET = ("anthropic", "claude-sonnet-5-5")
# Agents already running on their own code. Their functions do not read these settings yet.
OWN_CODE = {
    "AGT-08-SUPPORT": ("anthropic", "claude-opus-5-5"),
    "AGT-05-BIZDEV": ("openrouter", "deepseek/deepseek-v4.1-flash"),
    "AGT-13-EMAIL": ("openrouter", "deepseek/deepseek-v4.1-flash"),
}


def quote(text):
    tag = "seed"
    while f"${tag}$" in text:
        tag += "x"
    return f"${tag}${text}${tag}$"


def approvals(claude_md):
    match = re.search(r"^## Requires human approval\s*\n(.*?)(?=^## |\Z)", claude_md, re.M | re.S)
    return match.group(1).strip() if match else ""


def row(agent_id, name, role, instructions, approval, provider, model, group, runtime, order):
    values = [quote(agent_id), quote(name), quote(role), quote(instructions), quote(approval),
              quote(provider), quote(model), quote(group), quote(runtime), str(order)]
    return "  (" + ", ".join(values) + ")"


def main():
    registry = json.loads((AGENTS / "AGENT_REGISTRY.json").read_text(encoding="utf-8-sig"))
    rows = [row(registry["orchestrator"]["id"], "CRM AI Orchestrator", registry["orchestrator"]["role"],
                "", "", *SONNET, "Core", "not_connected", 0)]
    rows.append(row("AGT-14-CRM", "CRM Manager",
                    "Manages the CRM by chat: settings, integrations, database, UI and code changes, each approved by an admin.",
                    "", "Any production deployment, database change or credential change.",
                    "anthropic", "claude-opus-5-5", "Core", "not_connected", 1))
    order = 2
    for agent in registry["agents"]:
        claude_md = (AGENTS / agent["folder"] / "CLAUDE.md").read_text(encoding="utf-8-sig").strip()
        provider, model = OWN_CODE.get(agent["id"], SONNET)
        runtime = "own_code" if agent["id"] in OWN_CODE else "not_connected"
        rows.append(row(agent["id"], agent["name"], agent["mission"], claude_md, approvals(claude_md),
                        provider, model, agent["group"], runtime, order))
        order += 1
    rows.append(row("AGT-11-CEO", "CEO Agent",
                    "Captures the CEO's meetings, tasks, decisions and notes from chat, and answers from them.",
                    "", "", "openrouter", "deepseek/deepseek-v4.1-flash", "Client & Support", "own_code", order))
    sql = ("-- Generated by build_agent_seed.py. Run after 002_agents.sql. Never overwrites saved settings.\n"
           "insert into public.agents (id, name, role, instructions, approval_rules, provider, model, group_name, runtime, sort_order) values\n"
           + ",\n".join(rows) + "\non conflict (id) do nothing;\n")
    OUT.write_text(sql, encoding="utf-8", newline="\n")
    print(f"{len(rows)} agents written to {OUT.name}")


if __name__ == "__main__":
    main()
