// Writes tokens.css from tokens.json. Every name carries --abm- so the rest of the CRM is not affected.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const at = (name) => fileURLToPath(new URL(name, import.meta.url));
const t = JSON.parse(readFileSync(at("tokens.json"), "utf8"));
const lines = [
  ...Object.entries(t.color).map(([k, v]) => `--abm-${k}: ${v};`),
  `--abm-font: ${t.font.sans};`,
  ...Object.entries(t.type).flatMap(([k, v]) => [`--abm-${k}: ${v.size}px;`, `--abm-${k}-line: ${v.line}px;`, `--abm-${k}-weight: ${v.weight};`]),
  ...t.space.map((v, i) => `--abm-space-${i}: ${v}px;`),
  ...Object.entries(t.radius).map(([k, v]) => `--abm-radius-${k}: ${v}px;`),
  ...Object.entries(t.layout).map(([k, v]) => `--abm-${k}: ${v}px;`),
  ...Object.entries(t.shadow).map(([k, v]) => `--abm-${k}: ${v};`),
  `--abm-fast: ${t.motion.fast};`,
];
writeFileSync(at("tokens.css"), `/* Generated by build-tokens.mjs from tokens.json. Do not edit by hand. */\n:root {\n${lines.map((l) => `  ${l}`).join("\n")}\n}\n`);
