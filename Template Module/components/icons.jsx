// Shared line-icon set (Lucide-style) so the app uses consistent SVG icons
// instead of OS emoji. Inherits color via currentColor; size defaults to 18.
function Svg({ size = 18, children, ...rest }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      {...rest}
    >
      {children}
    </svg>
  );
}

